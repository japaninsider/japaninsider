let currentLang = localStorage.getItem("japanInsiderLang");
if (!currentLang) currentLang = navigator.language?.toLowerCase().startsWith("ja") ? "ja" : "en";

function t(key){ return translations[currentLang]?.[key] ?? translations.en[key] ?? key; }

function applyLanguage(lang){
  currentLang = lang;
  localStorage.setItem("japanInsiderLang", lang);
  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.dataset.i18n;
    el.textContent = translations[lang][key] ?? translations.en[key] ?? el.textContent;
  });
  document.querySelectorAll("[data-i18n-html]").forEach(el => {
    const key = el.dataset.i18nHtml;
    el.innerHTML = translations[lang][key] ?? translations.en[key] ?? el.innerHTML;
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    const key = el.dataset.i18nPlaceholder;
    el.placeholder = translations[lang][key] ?? translations.en[key] ?? el.placeholder;
  });
  document.querySelectorAll(".lang-btn").forEach(btn => btn.classList.toggle("active", btn.dataset.lang === lang));
  document.title = translations[lang]["meta.title"];
}

document.querySelectorAll(".lang-btn").forEach(btn => btn.addEventListener("click", () => applyLanguage(btn.dataset.lang)));

const menuButton = document.querySelector('.menu-toggle');
const nav = document.querySelector('.main-nav');
menuButton?.addEventListener('click', () => {
  const open = nav.classList.toggle('open');
  menuButton.setAttribute('aria-expanded', String(open));
});
document.querySelectorAll('.main-nav a').forEach(a => a.addEventListener('click', () => nav.classList.remove('open')));

document.querySelectorAll('[data-plan]').forEach(link => {
  link.addEventListener('click', () => {
    const select = document.getElementById('planSelect');
    if (select) select.value = link.dataset.plan;
  });
});

const form = document.getElementById('contactForm');
const status = document.getElementById('formStatus');
form?.addEventListener('submit', e => {
  e.preventDefault();
  if (CONTACT_EMAIL.includes('replace-with-your-email')) {
    status.textContent = t("status.owner");
    return;
  }
  const data = new FormData(form);
  const subject = `${t("mail.subject")} — ${data.get('plan')}`;
  const body = `${t("mail.name")}: ${data.get('name')}\n${t("mail.email")}: ${data.get('email')}\n${t("mail.plan")}: ${data.get('plan')}\n\n${t("mail.details")}:\n${data.get('message')}`;
  window.location.href = `mailto:${encodeURIComponent(CONTACT_EMAIL)}?subject=${encodeURIComponent(subject)}&body=${encodeURIComponent(body)}`;
  status.textContent = t("status.open");
});

document.getElementById('year').textContent = new Date().getFullYear();

const observer = new IntersectionObserver(entries => {
  entries.forEach(entry => {
    if (entry.isIntersecting) {
      entry.target.classList.add('visible');
      observer.unobserve(entry.target);
    }
  });
}, { threshold: 0.1 });
document.querySelectorAll('.reveal').forEach(el => observer.observe(el));

